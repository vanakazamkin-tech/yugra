create table if not exists public.municipal_facilities (
  id uuid primary key default gen_random_uuid(),
  municipality_id text not null references public.municipalities(id) on delete cascade,
  source_id text not null references public.data_sources(id),
  external_id text not null,
  facility_category text not null,
  name_full text not null,
  name_short text,
  address text,
  postal_code text,
  latitude numeric,
  longitude numeric,
  phone text,
  working_hours text,
  license_info text,
  ownership text,
  staffing_percent numeric,
  annual_attendance numeric,
  source_updated_at date,
  source_url text not null,
  source_payload jsonb not null default '{}'::jsonb check (jsonb_typeof(source_payload)='object'),
  verification_status text not null default 'needs_review'
    check (verification_status in ('verified','needs_review')),
  retrieved_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (source_id, external_id)
);
create index if not exists municipal_facilities_category_idx
  on public.municipal_facilities(facility_category, municipality_id);
create index if not exists municipal_facilities_geo_idx
  on public.municipal_facilities(latitude, longitude);
alter table public.municipal_facilities enable row level security;
drop policy if exists "Public can read verified municipal facilities" on public.municipal_facilities;
create policy "Public can read verified municipal facilities" on public.municipal_facilities
  for select to anon, authenticated using (verification_status='verified');
revoke insert, update, delete on public.municipal_facilities from anon, authenticated;
grant select on public.municipal_facilities to anon, authenticated;

